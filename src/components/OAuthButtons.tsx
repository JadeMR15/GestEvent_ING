export function OAuthButtons() {
  const [pending, setPending] = useState<OAuthProvider | null>(null);

  async function handle(provider: OAuthProvider) {
    setPending(provider);
    try {
      await signInWithProvider(provider);
    } catch (e) {
      toast.error(e instanceof Error ? e.message : "Connexion impossible.");
    } finally {
      // Sur le site la page change ; dans l'app la suite arrive via le lien de retour.
      setPending(null);
    }
  }

  return (
    <div className="space-y-3">
      <div className="flex items-center gap-3 py-1 text-xs uppercase text-muted-foreground">
        <span className="h-px flex-1 bg-border" />
        ou
        <span className="h-px flex-1 bg-border" />
      </div>
      <Button type="button" variant="outline" className="w-full" disabled={pending !== null} onClick={() => handle("google")}>
        {pending === "google" ? <Loader2 className="mr-2 h-4 w-4 animate-spin" /> : <span className="mr-2"><GoogleIcon /></span>}
        Continuer avec Google
      </Button>
      <Button type="button" variant="outline" className="w-full" disabled={pending !== null} onClick={() => handle("apple")}>
        {pending === "apple" ? <Loader2 className="mr-2 h-4 w-4 animate-spin" /> : <span className="mr-2"><AppleIcon /></span>}
        Continuer avec Apple
      </Button>
    </div>
  );
}
